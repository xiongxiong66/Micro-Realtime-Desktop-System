/* USER CODE BEGIN Header_Oled_Task */
/**
* @brief Function implementing the oled thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_Oled_Task */
void Oled_Task(void *argument)
{
/* USER CODE BEGIN Oled_Task */
  CursorMsg_t msg;

  /* Infinite loop */
  for(;;)
  {
    if (osMessageQueueGet(cursorHandle, &msg, NULL, 0) == osOK)
    {
      OLED_Clear();

      int16_t cx = (int16_t)msg.cursor_x;
      int16_t cy = (int16_t)msg.cursor_y;

      for (int16_t dy = -3; dy <= 3; dy++)
      {
        for (int16_t dx = -3; dx <= 3; dx++)
        {
          int16_t px = cx + dx;
          int16_t py = cy + dy;
          if (dx*dx + dy*dy <= 9
           && px >= 0 && px < (int16_t)OLED_WIDTH
           && py >= 0 && py < (int16_t)OLED_HEIGHT)
          {
            OLED_DrawPixel((uint8_t)px, (uint8_t)py, OLED_WHITE);
          }
        }
      }

      OLED_SetCursor(0, 56);
      OLED_PrintString("X:");
      OLED_PrintNum(msg.cursor_x, 10);
      OLED_PrintString(" Y:");
      OLED_PrintNum(msg.cursor_y, 10);

      OLED_Display();
    }
    osDelay(15);
  }
 /* USER CODE END Oled_Task */
}

/* USER CODE BEGIN Header_Sw_Adc_Task */
/**
* @brief Function implementing the Sw_Adc thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_Sw_Adc_Task */
void Sw_Adc_Task(void *argument)
{
/* USER CODE BEGIN Sw_Adc_Task */
  uint16_t adc_x, adc_y;
  int16_t cursor_x = 64;
  int16_t cursor_y = 32;
  CursorMsg_t msg;
  static uint8_t prev_btn_state = 1;
  uint8_t button_pressed = 0;
  osDelay(100);

  /* Infinite loop */
  for(;;)
  {
    if (BSP_ADC_ReadDual(&adc_x, &adc_y) != BSP_ADC_OK)
    {
      osDelay(20);
      continue;
    }

    int16_t dx = (int16_t)adc_x - 2048;
    int16_t dy = (int16_t)adc_y - 2048;

  
    if (dx > 180 && cursor_x > 0) 
    {
      int16_t step = (dx - 180) / 700 + 1;

      cursor_x -= step;
    }
    if (dx < -180 && cursor_x < 127)  
    {
      int16_t step = (-dx - 180) / 700 + 1;

      cursor_x += step;
    }
    
   
    if (dy > 180 && cursor_y < 63)  
    {
      int16_t step = (dy - 180) / 700 + 1;

      cursor_y += step;
    }
    if (dy < -180 && cursor_y > 0) 
    {
      int16_t step = (-dy - 180) / 700 + 1;

      cursor_y -= step;
    }
    
    if (cursor_x > 127) cursor_x = 127;
    if (cursor_y > 63) cursor_y = 63;
    if (cursor_x < 0) cursor_x = 0;
    if (cursor_y < 0) cursor_y = 0;

    uint8_t curr_btn = HAL_GPIO_ReadPin(SW_GPIO_Port, SW_Pin);
    if (curr_btn == 0 && prev_btn_state == 1)
      button_pressed = 1;
    else if (curr_btn == 1 && prev_btn_state == 0)
      button_pressed = 0;
    prev_btn_state = curr_btn;

    msg.cursor_x       = cursor_x;
    msg.cursor_y       = cursor_y;
    msg.button_pressed = button_pressed;
    osMessageQueuePut(cursorHandle, &msg, 0, 0);
    osDelay(20);
  }
 /* USER CODE END Sw_Adc_Task */
}

